// Builds what the import map in index.html points at. `vue` and `vuetify` are thin
// re-exports of the host's live instances, so plugins share them. The components
// bundle is real code, because the main build tree-shakes Vuetify's components.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vue from '@vitejs/plugin-vue';
import { build } from 'vite';
import vuetify from 'vite-plugin-vuetify';
import * as Vue from 'vue';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'dist/static/plugin-shims');

// The exports of 'vuetify' a plugin can reasonably call. Plugins don't create
// their own Vuetify instance, so createVuetify is left out on purpose.
const VUETIFY_EXPORTS = ['useDate', 'useDefaults', 'useDisplay', 'useGoTo', 'useLayout', 'useLocale', 'useRtl', 'useTheme'];

function reexports(names, source) {
  const list = names.filter((n) => /^[A-Za-z_$][\w$]*$/.test(n) && n !== 'default').join(', ');
  return `// Generated by scripts/build-plugin-shims.mjs.\nexport const { ${list} } = globalThis.__LP_HOST__.${source};\n`;
}

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'vue.js'), reexports(Object.keys(Vue), 'Vue'));
writeFileSync(join(outDir, 'vuetify.js'), reexports(VUETIFY_EXPORTS, 'Vuetify'));

await build({
  root,
  configFile: false,
  publicDir: false,
  logLevel: 'warn',
  plugins: [vue(), vuetify({ autoImport: false, styles: { configFile: 'src/styles/settings.scss' } })],
  define: {
    __VUE_OPTIONS_API__: true,
    __VUE_PROD_DEVTOOLS__: false,
    __VUE_PROD_HYDRATION_MISMATCH_DETAILS__: false,
    'process.env.NODE_ENV': '"production"',
  },
  build: {
    outDir,
    emptyOutDir: false,
    cssCodeSplit: false,
    lib: {
      entry: join(root, 'src/pluginHost/shims/vuetify-components.js'),
      formats: ['es'],
      fileName: () => 'vuetify-components.js',
      cssFileName: 'vuetify-components',
    },
    rollupOptions: {
      external: ['vue'],
    },
  },
});
